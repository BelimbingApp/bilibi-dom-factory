-- Bilimbi ProductionExecution capture, final schema. Inventory and User IDs
-- are opaque owner-validated references; no sibling tables are reached here.
CREATE TABLE factory_wastage_reasons (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 tenant_id bigint NOT NULL, company_id bigint NOT NULL,
 code varchar(64) NOT NULL CHECK(code ~ '^[A-Z0-9][A-Z0-9_.-]*$'),
 label varchar(255) NOT NULL CHECK(length(btrim(label)) > 0),
 active boolean NOT NULL DEFAULT true,
 FOREIGN KEY(tenant_id,company_id) REFERENCES companies(tenant_id,id),
 UNIQUE(tenant_id,company_id,code), UNIQUE(tenant_id,company_id,id)
);
CREATE TABLE factory_labour_roles (LIKE factory_wastage_reasons INCLUDING ALL);
ALTER TABLE factory_labour_roles ADD FOREIGN KEY(tenant_id,company_id) REFERENCES companies(tenant_id,id);
CREATE TABLE factory_measurement_types (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 tenant_id bigint NOT NULL, company_id bigint NOT NULL,
 code varchar(64) NOT NULL CHECK(code ~ '^[A-Z0-9][A-Z0-9_.-]*$'),
 label varchar(255) NOT NULL CHECK(length(btrim(label)) > 0),
 active boolean NOT NULL DEFAULT true,
 value_type text NOT NULL CHECK(value_type IN ('string','integer','decimal','boolean')),
 unit varchar(32), minimum numeric(24,12), maximum numeric(24,12), target numeric(24,12),
 CHECK(minimum <= maximum),
 CHECK(value_type IN ('integer','decimal') OR (unit IS NULL AND minimum IS NULL AND maximum IS NULL AND target IS NULL)),
 FOREIGN KEY(tenant_id,company_id) REFERENCES companies(tenant_id,id),
 UNIQUE(tenant_id,company_id,code), UNIQUE(tenant_id,company_id,id)
);
CREATE TABLE factory_wastage_records (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 tenant_id bigint NOT NULL, company_id bigint NOT NULL,
 order_id bigint NOT NULL, execution_id bigint NOT NULL,
 request_id varchar(240) NOT NULL CHECK(length(btrim(request_id)) > 0), request_fingerprint text NOT NULL,
 reason_id bigint NOT NULL, item_id bigint NOT NULL, location_id bigint NOT NULL,
 identity_id bigint, quantity numeric(24,12) NOT NULL, unit_id bigint NOT NULL,
 observation text NOT NULL, note text, occurred_at timestamptz NOT NULL,
 inventory_transaction_id bigint,
 corrects_id bigint UNIQUE, correction_reason text,
 recorded_by_type text NOT NULL, recorded_by_id bigint NOT NULL, recorded_by_acting_for_user_id bigint,
 inserted_at timestamptz NOT NULL DEFAULT now(),
 CHECK((corrects_id IS NULL AND quantity > 0 AND inventory_transaction_id IS NOT NULL AND correction_reason IS NULL)
    OR (corrects_id IS NOT NULL AND quantity >= 0 AND correction_reason IS NOT NULL AND length(btrim(correction_reason)) > 0)),
 FOREIGN KEY(tenant_id,company_id) REFERENCES companies(tenant_id,id),
 FOREIGN KEY(tenant_id,company_id,order_id) REFERENCES factory_production_orders(tenant_id,company_id,id),
 FOREIGN KEY(tenant_id,company_id,execution_id) REFERENCES factory_operation_executions(tenant_id,company_id,id),
 FOREIGN KEY(tenant_id,company_id,reason_id) REFERENCES factory_wastage_reasons(tenant_id,company_id,id),
 FOREIGN KEY(tenant_id,company_id,corrects_id) REFERENCES factory_wastage_records(tenant_id,company_id,id),
 UNIQUE(tenant_id,company_id,id), UNIQUE(tenant_id,company_id,request_id)
);
CREATE INDEX factory_wastage_records_run ON factory_wastage_records(tenant_id,company_id,execution_id,id);
CREATE TABLE factory_labour_entries (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 tenant_id bigint NOT NULL, company_id bigint NOT NULL,
 order_id bigint NOT NULL, execution_id bigint,
 request_id varchar(240) NOT NULL CHECK(length(btrim(request_id)) > 0), request_fingerprint text NOT NULL,
 worker_user_id bigint NOT NULL, role_id bigint NOT NULL,
 started_at timestamptz NOT NULL, stopped_at timestamptz, note text,
 corrects_id bigint UNIQUE, correction_reason text,
 recorded_by_type text NOT NULL, recorded_by_id bigint NOT NULL, recorded_by_acting_for_user_id bigint,
 stopped_by_type text, stopped_by_id bigint, stopped_by_acting_for_user_id bigint,
 inserted_at timestamptz NOT NULL DEFAULT now(),
 CHECK(stopped_at >= started_at),
 CHECK((stopped_at IS NULL AND stopped_by_type IS NULL AND stopped_by_id IS NULL AND stopped_by_acting_for_user_id IS NULL)
    OR (stopped_at IS NOT NULL AND stopped_by_type IS NOT NULL AND stopped_by_id IS NOT NULL)),
 CHECK((corrects_id IS NULL AND correction_reason IS NULL) OR
       (corrects_id IS NOT NULL AND correction_reason IS NOT NULL AND length(btrim(correction_reason)) > 0)),
 FOREIGN KEY(tenant_id,company_id) REFERENCES companies(tenant_id,id),
 FOREIGN KEY(tenant_id,company_id,order_id) REFERENCES factory_production_orders(tenant_id,company_id,id),
 FOREIGN KEY(tenant_id,company_id,execution_id) REFERENCES factory_operation_executions(tenant_id,company_id,id),
 FOREIGN KEY(tenant_id,company_id,role_id) REFERENCES factory_labour_roles(tenant_id,company_id,id),
 FOREIGN KEY(tenant_id,company_id,corrects_id) REFERENCES factory_labour_entries(tenant_id,company_id,id),
 UNIQUE(tenant_id,company_id,id), UNIQUE(tenant_id,company_id,request_id)
);
CREATE INDEX factory_labour_entries_worker ON factory_labour_entries(tenant_id,company_id,worker_user_id);
CREATE TABLE factory_measurements (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 tenant_id bigint NOT NULL, company_id bigint NOT NULL,
 order_id bigint NOT NULL, execution_id bigint NOT NULL,
 request_id varchar(240) NOT NULL CHECK(length(btrim(request_id)) > 0), request_fingerprint text NOT NULL,
 measurement_type_id bigint NOT NULL, identity_id bigint,
 value_type text NOT NULL, value text NOT NULL, unit varchar(32),
 minimum numeric(24,12), maximum numeric(24,12), target numeric(24,12), out_of_range boolean,
 measured_at timestamptz NOT NULL, note text,
 corrects_id bigint UNIQUE, correction_reason text,
 recorded_by_type text NOT NULL, recorded_by_id bigint NOT NULL, recorded_by_acting_for_user_id bigint,
 inserted_at timestamptz NOT NULL DEFAULT now(),
 CHECK((corrects_id IS NULL AND correction_reason IS NULL) OR
       (corrects_id IS NOT NULL AND correction_reason IS NOT NULL AND length(btrim(correction_reason)) > 0)),
 FOREIGN KEY(tenant_id,company_id) REFERENCES companies(tenant_id,id),
 FOREIGN KEY(tenant_id,company_id,order_id) REFERENCES factory_production_orders(tenant_id,company_id,id),
 FOREIGN KEY(tenant_id,company_id,execution_id) REFERENCES factory_operation_executions(tenant_id,company_id,id),
 FOREIGN KEY(tenant_id,company_id,measurement_type_id) REFERENCES factory_measurement_types(tenant_id,company_id,id),
 FOREIGN KEY(tenant_id,company_id,corrects_id) REFERENCES factory_measurements(tenant_id,company_id,id),
 UNIQUE(tenant_id,company_id,id), UNIQUE(tenant_id,company_id,request_id)
);
CREATE INDEX factory_measurements_run ON factory_measurements(tenant_id,company_id,execution_id,id);
CREATE TRIGGER factory_wastage_records_immutable BEFORE UPDATE OR DELETE OR TRUNCATE
 ON factory_wastage_records FOR EACH STATEMENT EXECUTE FUNCTION factory_production_execution_refuse_change();
CREATE TRIGGER factory_measurements_immutable BEFORE UPDATE OR DELETE OR TRUNCATE
 ON factory_measurements FOR EACH STATEMENT EXECUTE FUNCTION factory_production_execution_refuse_change();
CREATE FUNCTION factory_labour_close_only() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
 IF OLD.stopped_at IS NULL AND NEW.stopped_at IS NOT NULL AND
    (to_jsonb(OLD) - ARRAY['stopped_at','stopped_by_type','stopped_by_id','stopped_by_acting_for_user_id']) =
    (to_jsonb(NEW) - ARRAY['stopped_at','stopped_by_type','stopped_by_id','stopped_by_acting_for_user_id']) THEN
  RETURN NEW;
 END IF;
 RAISE EXCEPTION 'factory_labour_entries are immutable except for closing an open entry';
END;
$$;
CREATE TRIGGER factory_labour_entries_close_only BEFORE UPDATE ON factory_labour_entries
 FOR EACH ROW EXECUTE FUNCTION factory_labour_close_only();
CREATE TRIGGER factory_labour_entries_immutable BEFORE DELETE OR TRUNCATE ON factory_labour_entries
 FOR EACH STATEMENT EXECUTE FUNCTION factory_production_execution_refuse_change();

-- Bilimbi ProductionExecution's final schema for orders, completed operation
-- executions and material hold overrides. Product, resource and Inventory
-- references are opaque IDs the facades validate; this module does not reach
-- into its siblings' tables.
CREATE TABLE factory_production_orders (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 tenant_id bigint NOT NULL,
 company_id bigint NOT NULL,
 code varchar(255) NOT NULL CHECK(length(btrim(code)) > 0),
 kind varchar(255) NOT NULL,
 product_id bigint NOT NULL CHECK(product_id > 0),
 formula_version integer NOT NULL,
 routing_version integer NOT NULL,
 demand_ref varchar(255),
 inserted_at timestamptz NOT NULL DEFAULT now(),
 updated_at timestamptz NOT NULL DEFAULT now(),
 FOREIGN KEY(tenant_id,company_id) REFERENCES companies(tenant_id,id) ON DELETE RESTRICT,
 CONSTRAINT factory_production_orders_company_code_unique UNIQUE(company_id,code),
 CONSTRAINT factory_production_orders_kind CHECK(kind IN ('order','batch')),
 CONSTRAINT factory_production_orders_versions CHECK(formula_version > 0 AND routing_version > 0),
 UNIQUE(tenant_id,company_id,id)
);
CREATE TABLE factory_operation_executions (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 tenant_id bigint NOT NULL,
 company_id bigint NOT NULL,
 order_id bigint NOT NULL,
 request_id varchar(255) NOT NULL CHECK(length(btrim(request_id)) > 0),
 request_fingerprint varchar(255) NOT NULL,
 source varchar(255) NOT NULL,
 operation_code varchar(255) NOT NULL,
 resource_id bigint NOT NULL CHECK(resource_id > 0),
 operator_type varchar(255) NOT NULL CHECK(length(operator_type) > 0),
 operator_id bigint NOT NULL CHECK(operator_id >= 0),
 started_at timestamptz NOT NULL,
 completed_at timestamptz NOT NULL,
 inputs jsonb NOT NULL CHECK(jsonb_typeof(inputs)='array'),
 outputs jsonb NOT NULL CHECK(jsonb_typeof(outputs)='array'),
 variance jsonb CHECK(variance IS NULL OR jsonb_typeof(variance)='object'),
 evidence text NOT NULL CHECK(length(evidence) > 0),
 inventory_transaction_id bigint NOT NULL CHECK(inventory_transaction_id > 0),
 formula_version integer NOT NULL,
 routing_version integer NOT NULL,
 inserted_at timestamptz NOT NULL DEFAULT now(),
 FOREIGN KEY(tenant_id,company_id) REFERENCES companies(tenant_id,id) ON DELETE RESTRICT,
 CONSTRAINT factory_operation_executions_order_foreign FOREIGN KEY(tenant_id,company_id,order_id)
  REFERENCES factory_production_orders(tenant_id,company_id,id) ON DELETE RESTRICT,
 CONSTRAINT factory_operation_executions_company_request_unique UNIQUE(company_id,request_id),
 CONSTRAINT factory_operation_executions_time CHECK(started_at <= completed_at),
 CONSTRAINT factory_operation_executions_source CHECK(source IN ('live','import')),
 CONSTRAINT factory_operation_executions_versions CHECK(formula_version > 0 AND routing_version > 0),
 CONSTRAINT factory_operation_executions_inputs_or_outputs CHECK(jsonb_array_length(inputs) > 0 OR jsonb_array_length(outputs) > 0),
 UNIQUE(tenant_id,company_id,id)
);
CREATE INDEX factory_operation_executions_order_index
 ON factory_operation_executions(tenant_id,company_id,order_id,completed_at DESC,id DESC);
CREATE INDEX factory_operation_executions_transaction_index
 ON factory_operation_executions(tenant_id,company_id,inventory_transaction_id);
CREATE TABLE factory_material_hold_overrides (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 tenant_id bigint NOT NULL,
 company_id bigint NOT NULL,
 execution_id bigint NOT NULL,
 inventory_transaction_id bigint NOT NULL CHECK(inventory_transaction_id > 0),
 source_transaction_id bigint NOT NULL CHECK(source_transaction_id > 0),
 identity_id bigint NOT NULL CHECK(identity_id > 0),
 item_id bigint NOT NULL CHECK(item_id > 0),
 source varchar(255) NOT NULL,
 actor_type varchar(255),
 actor_id bigint,
 acting_for_user_id bigint,
 recorded_by_type varchar(255) NOT NULL,
 recorded_by_id bigint NOT NULL,
 recorded_by_acting_for_user_id bigint,
 reason text NOT NULL,
 evidence text,
 occurred_at timestamptz NOT NULL,
 FOREIGN KEY(tenant_id,company_id) REFERENCES companies(tenant_id,id) ON DELETE RESTRICT,
 CONSTRAINT factory_material_hold_overrides_execution_foreign FOREIGN KEY(tenant_id,company_id,execution_id)
  REFERENCES factory_operation_executions(tenant_id,company_id,id) ON DELETE RESTRICT,
 CONSTRAINT factory_material_hold_overrides_execution_identity_unique UNIQUE(execution_id,identity_id),
 CONSTRAINT factory_material_hold_overrides_reason CHECK(length(btrim(reason)) > 0),
 CONSTRAINT factory_material_hold_overrides_source CHECK(
  (source = 'live' AND evidence IS NULL AND actor_type = recorded_by_type
   AND actor_id = recorded_by_id
   AND acting_for_user_id IS NOT DISTINCT FROM recorded_by_acting_for_user_id)
  OR (source = 'import' AND length(btrim(evidence)) > 0))
);
-- Executions and their override evidence are never edited or removed; a
-- mistake is corrected by a new posting, not by rewriting the record.
CREATE FUNCTION factory_production_execution_refuse_change() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
 RAISE EXCEPTION '% are immutable', TG_TABLE_NAME;
END;
$$;
CREATE TRIGGER factory_operation_executions_immutable BEFORE UPDATE OR DELETE OR TRUNCATE
 ON factory_operation_executions FOR EACH STATEMENT EXECUTE FUNCTION factory_production_execution_refuse_change();
CREATE TRIGGER factory_material_hold_overrides_immutable BEFORE UPDATE OR DELETE OR TRUNCATE
 ON factory_material_hold_overrides FOR EACH STATEMENT EXECUTE FUNCTION factory_production_execution_refuse_change();

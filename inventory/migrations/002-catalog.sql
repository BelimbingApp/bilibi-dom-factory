-- The item catalog: the end state of Bilimbi's commerce_inventory_items (the
-- item master), factory_inventory_material_types, factory_inventory_materials
-- and factory_inventory_unit_conversions, each with its retirement.
--
-- The item master keeps Belimbing's columns and durable table name, without
-- the adopted column defaults for status and currency: both are the company's
-- item settings, and Inventory writes them explicitly. Every reference is
-- composite with company_id, so a row can only name a record of its own
-- company.
CREATE TABLE commerce_inventory_items (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 tenant_id bigint NOT NULL,
 company_id bigint NOT NULL,
 -- Opaque references to a Commerce Catalog Inventory does not own.
 category_id bigint,
 product_template_id bigint,
 sku varchar(255) NOT NULL CHECK(sku = upper(btrim(sku)) AND length(sku) BETWEEN 1 AND 64),
 status varchar(255) NOT NULL CHECK(length(btrim(status)) > 0 AND status = btrim(status)),
 title varchar(255) NOT NULL CHECK(length(btrim(title)) > 0),
 description text,
 quantity_on_hand integer NOT NULL CHECK(quantity_on_hand BETWEEN 0 AND 999999),
 storage_location varchar(255) CHECK(storage_location IS NULL OR (storage_location = btrim(storage_location) AND storage_location <> '')),
 notes text CHECK(notes IS NULL OR length(notes) <= 5000),
 unit_cost_amount bigint CHECK(unit_cost_amount >= 0),
 target_price_amount bigint CHECK(target_price_amount >= 0),
 currency_code char(3) NOT NULL CHECK(currency_code ~ '^[A-Z]{3}$'),
 created_at timestamptz NOT NULL DEFAULT now(),
 updated_at timestamptz NOT NULL DEFAULT now(),
 CONSTRAINT commerce_inventory_items_company_foreign FOREIGN KEY(tenant_id,company_id) REFERENCES companies(tenant_id,id) ON DELETE RESTRICT,
 CONSTRAINT commerce_inventory_items_company_id_sku_unique UNIQUE(company_id,sku),
 CONSTRAINT commerce_inventory_items_company_id_id_unique UNIQUE(company_id,id)
);
CREATE INDEX commerce_inventory_items_company_id_status_index ON commerce_inventory_items(company_id,status);
CREATE INDEX commerce_inventory_items_company_id_created_at_index ON commerce_inventory_items(company_id,created_at);

-- A company's material types. Which types exist, and the properties each
-- defines, is that company's configuration: nothing here names one.
CREATE TABLE factory_inventory_material_types (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 tenant_id bigint NOT NULL,
 company_id bigint NOT NULL,
 code varchar(64) NOT NULL CHECK(code = upper(btrim(code)) AND length(code) BETWEEN 1 AND 64),
 name varchar(255) NOT NULL CHECK(length(btrim(name)) > 0),
 property_definitions jsonb NOT NULL DEFAULT '[]' CHECK(jsonb_typeof(property_definitions) = 'array'),
 retired_at timestamptz,
 created_at timestamptz NOT NULL DEFAULT now(),
 updated_at timestamptz NOT NULL DEFAULT now(),
 CONSTRAINT factory_inventory_material_types_company_foreign FOREIGN KEY(tenant_id,company_id) REFERENCES companies(tenant_id,id) ON DELETE RESTRICT,
 CONSTRAINT factory_inventory_material_types_company_id_code_unique UNIQUE(company_id,code),
 CONSTRAINT factory_inventory_material_types_company_id_id_unique UNIQUE(company_id,id)
);

-- An item stocked as a material, once, in a native unit that never changes.
CREATE TABLE factory_inventory_materials (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 tenant_id bigint NOT NULL,
 company_id bigint NOT NULL,
 item_id bigint NOT NULL,
 native_unit_id bigint NOT NULL,
 material_type_id bigint,
 properties jsonb NOT NULL DEFAULT '{}',
 retired_at timestamptz,
 created_at timestamptz NOT NULL DEFAULT now(),
 updated_at timestamptz NOT NULL DEFAULT now(),
 CONSTRAINT factory_inventory_materials_company_foreign FOREIGN KEY(tenant_id,company_id) REFERENCES companies(tenant_id,id) ON DELETE RESTRICT,
 CONSTRAINT factory_inventory_materials_item_id_foreign FOREIGN KEY(company_id,item_id) REFERENCES commerce_inventory_items(company_id,id) ON DELETE RESTRICT,
 CONSTRAINT factory_inventory_materials_native_unit_id_foreign FOREIGN KEY(company_id,native_unit_id) REFERENCES factory_inventory_units(company_id,id) ON DELETE RESTRICT,
 CONSTRAINT factory_inventory_materials_material_type_id_fkey FOREIGN KEY(company_id,material_type_id) REFERENCES factory_inventory_material_types(company_id,id) ON DELETE RESTRICT,
 CONSTRAINT factory_inventory_materials_item_id_unique UNIQUE(item_id),
 CONSTRAINT factory_inventory_materials_company_id_id_unique UNIQUE(company_id,id),
 CONSTRAINT factory_inventory_materials_properties_shape CHECK(jsonb_typeof(properties) = 'object' AND (material_type_id IS NOT NULL OR properties = '{}'::jsonb))
);
CREATE INDEX factory_inventory_materials_company_id_native_unit_id_index ON factory_inventory_materials(company_id,native_unit_id);
CREATE INDEX factory_inventory_materials_company_id_material_type_id_index ON factory_inventory_materials(company_id,material_type_id);

-- One `unit_id` equals `factor` native units. A row never changes: a changed
-- factor is the next version, and earlier versions stay readable.
CREATE TABLE factory_inventory_unit_conversions (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 tenant_id bigint NOT NULL,
 company_id bigint NOT NULL,
 material_id bigint NOT NULL,
 unit_id bigint NOT NULL,
 version integer NOT NULL,
 factor numeric(24,12) NOT NULL,
 created_at timestamptz NOT NULL DEFAULT now(),
 CONSTRAINT factory_inventory_unit_conversions_company_foreign FOREIGN KEY(tenant_id,company_id) REFERENCES companies(tenant_id,id) ON DELETE RESTRICT,
 CONSTRAINT factory_inventory_unit_conversions_material_id_foreign FOREIGN KEY(company_id,material_id) REFERENCES factory_inventory_materials(company_id,id) ON DELETE RESTRICT,
 CONSTRAINT factory_inventory_unit_conversions_unit_id_foreign FOREIGN KEY(company_id,unit_id) REFERENCES factory_inventory_units(company_id,id) ON DELETE RESTRICT,
 CONSTRAINT factory_inventory_unit_conversions_material_unit_version_unique UNIQUE(material_id,unit_id,version),
 CONSTRAINT factory_inventory_unit_conversions_factor_positive CHECK(factor > 0),
 CONSTRAINT factory_inventory_unit_conversions_version_positive CHECK(version > 0)
);

-- An item keeps its company and SKU; a material keeps its company, item,
-- native unit and type; a material type keeps its company. Anything retired
-- stays retired.
CREATE FUNCTION factory_inventory_keep_catalog_identity() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
 IF NEW.id IS DISTINCT FROM OLD.id OR NEW.tenant_id IS DISTINCT FROM OLD.tenant_id
    OR NEW.company_id IS DISTINCT FROM OLD.company_id THEN
  RAISE EXCEPTION '% rows keep their company', TG_TABLE_NAME USING ERRCODE = 'integrity_constraint_violation';
 END IF;
 IF TG_TABLE_NAME = 'commerce_inventory_items' THEN
  IF NEW.sku IS DISTINCT FROM OLD.sku THEN
   RAISE EXCEPTION 'An item keeps its SKU' USING ERRCODE = 'integrity_constraint_violation';
  END IF;
  RETURN NEW;
 END IF;
 IF TG_TABLE_NAME = 'factory_inventory_materials' AND (NEW.item_id IS DISTINCT FROM OLD.item_id
    OR NEW.native_unit_id IS DISTINCT FROM OLD.native_unit_id OR NEW.material_type_id IS DISTINCT FROM OLD.material_type_id) THEN
  RAISE EXCEPTION 'A material keeps its item, native unit and type' USING ERRCODE = 'integrity_constraint_violation';
 END IF;
 IF OLD.retired_at IS NOT NULL AND NEW.retired_at IS DISTINCT FROM OLD.retired_at THEN
  RAISE EXCEPTION 'A retired % stays retired', TG_TABLE_NAME USING ERRCODE = 'integrity_constraint_violation';
 END IF;
 RETURN NEW;
END $$;
CREATE TRIGGER commerce_inventory_items_keep_identity BEFORE UPDATE ON commerce_inventory_items FOR EACH ROW EXECUTE FUNCTION factory_inventory_keep_catalog_identity();
CREATE TRIGGER factory_inventory_material_types_keep_identity BEFORE UPDATE ON factory_inventory_material_types FOR EACH ROW EXECUTE FUNCTION factory_inventory_keep_catalog_identity();
CREATE TRIGGER factory_inventory_materials_keep_identity BEFORE UPDATE ON factory_inventory_materials FOR EACH ROW EXECUTE FUNCTION factory_inventory_keep_catalog_identity();

-- Conversion versions are immutable: PostgreSQL refuses UPDATE, DELETE and
-- TRUNCATE, and a version names a unit other than the material's native one.
CREATE FUNCTION factory_inventory_conversions_append_only() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
 RAISE EXCEPTION 'Conversion versions are immutable; define the next version' USING ERRCODE = 'integrity_constraint_violation';
END $$;
CREATE TRIGGER factory_inventory_unit_conversions_append_only BEFORE UPDATE OR DELETE ON factory_inventory_unit_conversions FOR EACH ROW EXECUTE FUNCTION factory_inventory_conversions_append_only();
CREATE TRIGGER factory_inventory_unit_conversions_no_truncate BEFORE TRUNCATE ON factory_inventory_unit_conversions FOR EACH STATEMENT EXECUTE FUNCTION factory_inventory_conversions_append_only();

CREATE FUNCTION factory_inventory_conversions_not_native() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
 IF EXISTS (SELECT 1 FROM factory_inventory_materials WHERE id = NEW.material_id AND native_unit_id = NEW.unit_id) THEN
  RAISE EXCEPTION 'A conversion names a unit other than the native unit' USING ERRCODE = 'check_violation';
 END IF;
 RETURN NEW;
END $$;
CREATE TRIGGER factory_inventory_unit_conversions_not_native BEFORE INSERT ON factory_inventory_unit_conversions FOR EACH ROW EXECUTE FUNCTION factory_inventory_conversions_not_native();

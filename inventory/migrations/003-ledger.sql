-- Bilimbi Inventory's Material Transaction ledger, including weigh tickets.
-- Genealogy and identity columns arrive in XI3. All references stay company-local.
ALTER TABLE factory_inventory_unit_conversions ADD CONSTRAINT factory_inventory_conversions_company_id_id_unique UNIQUE(company_id,id);
ALTER TABLE factory_inventory_materials ADD CONSTRAINT factory_inventory_materials_native_identity_unique UNIQUE(company_id,id,native_unit_id);

CREATE TABLE factory_inventory_transactions (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 tenant_id bigint NOT NULL,
 company_id bigint NOT NULL,
 kind varchar(32) NOT NULL,
 request_id varchar(255) NOT NULL,
 request_fingerprint varchar(64) NOT NULL,
 actor_type varchar(64) NOT NULL,
 actor_id bigint NOT NULL,
 evidence text NOT NULL,
 receipt_measurement jsonb,
 reason text,
 corrects_transaction_id bigint,
 posting_authority varchar(255),
 operation_execution_ref varchar(255),
 order_or_batch_ref varchar(255),
 work_centre_ref varchar(255),
 shipment_ref varchar(255),
 destination_ref varchar(255),
 effective_at timestamptz NOT NULL,
 recorded_at timestamptz NOT NULL,
 CONSTRAINT factory_inventory_transactions_company_foreign FOREIGN KEY(tenant_id,company_id) REFERENCES companies(tenant_id,id),
 CONSTRAINT factory_inventory_transactions_company_id_id_unique UNIQUE(company_id,id),
 CONSTRAINT factory_inventory_transactions_company_id_request_id_unique UNIQUE(company_id,request_id),
 CONSTRAINT factory_inventory_transactions_corrects_foreign FOREIGN KEY(company_id,corrects_transaction_id) REFERENCES factory_inventory_transactions(company_id,id),
 CONSTRAINT factory_inventory_transactions_kind CHECK(kind IN ('receipt','transfer','consumption','output','correction','transform')),
 CONSTRAINT factory_inventory_transactions_correction_reference CHECK(
   (kind='correction' AND corrects_transaction_id IS NOT NULL AND reason IS NOT NULL)
   OR (kind<>'correction' AND corrects_transaction_id IS NULL AND reason IS NULL)),
 CONSTRAINT factory_inventory_transactions_late_entry CHECK(effective_at<=recorded_at)
);
CREATE INDEX factory_inventory_transactions_recorded_index ON factory_inventory_transactions(company_id,recorded_at);
CREATE INDEX factory_inventory_transactions_corrects_index ON factory_inventory_transactions(company_id,corrects_transaction_id);

CREATE TABLE factory_inventory_transaction_entries (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 tenant_id bigint NOT NULL,
 company_id bigint NOT NULL,
 transaction_id bigint NOT NULL,
 role varchar(16) NOT NULL,
 material_id bigint,
 location_id bigint,
 native_quantity numeric(36,12) NOT NULL,
 native_unit_id bigint NOT NULL,
 recorded_quantity numeric(24,12),
 recorded_unit_id bigint,
 conversion_id bigint,
 observation varchar(16),
 output_role varchar(64),
 evidence text,
 reconciliation_basis text,
 CONSTRAINT factory_inventory_entries_company_foreign FOREIGN KEY(tenant_id,company_id) REFERENCES companies(tenant_id,id),
 CONSTRAINT factory_inventory_entries_transaction_foreign FOREIGN KEY(company_id,transaction_id) REFERENCES factory_inventory_transactions(company_id,id),
 CONSTRAINT factory_inventory_entries_material_foreign FOREIGN KEY(company_id,material_id,native_unit_id) REFERENCES factory_inventory_materials(company_id,id,native_unit_id),
 CONSTRAINT factory_inventory_entries_location_foreign FOREIGN KEY(company_id,location_id) REFERENCES factory_inventory_locations(company_id,id),
 CONSTRAINT factory_inventory_entries_native_unit_foreign FOREIGN KEY(company_id,native_unit_id) REFERENCES factory_inventory_units(company_id,id),
 CONSTRAINT factory_inventory_entries_recorded_unit_foreign FOREIGN KEY(company_id,recorded_unit_id) REFERENCES factory_inventory_units(company_id,id),
 CONSTRAINT factory_inventory_entries_conversion_foreign FOREIGN KEY(company_id,conversion_id) REFERENCES factory_inventory_unit_conversions(company_id,id),
 CONSTRAINT factory_inventory_entries_role CHECK(role IN ('stock','boundary','variance')),
 CONSTRAINT factory_inventory_entries_shape CHECK(CASE role
  WHEN 'stock' THEN material_id IS NOT NULL AND location_id IS NOT NULL AND recorded_quantity IS NOT NULL AND recorded_unit_id IS NOT NULL AND observation IS NOT NULL AND reconciliation_basis IS NULL
  WHEN 'boundary' THEN material_id IS NOT NULL AND location_id IS NULL AND recorded_quantity IS NULL AND observation IS NULL AND reconciliation_basis IS NULL
  WHEN 'variance' THEN material_id IS NULL AND location_id IS NULL AND recorded_quantity IS NULL AND observation IS NULL AND evidence IS NOT NULL AND reconciliation_basis IS NOT NULL END),
 CONSTRAINT factory_inventory_entries_observation CHECK(observation IN ('measured','declared','counted','derived')),
 CONSTRAINT factory_inventory_entries_quantities CHECK(native_quantity<>0 AND native_quantity<>'NaN'::numeric AND (recorded_quantity IS NULL OR (recorded_quantity>0 AND recorded_quantity<>'NaN'::numeric)))
);
CREATE INDEX factory_inventory_entries_transaction_index ON factory_inventory_transaction_entries(company_id,transaction_id);
CREATE INDEX factory_inventory_entries_stock_index ON factory_inventory_transaction_entries(material_id,location_id) WHERE location_id IS NOT NULL;

CREATE FUNCTION factory_inventory_ledger_refuse_change() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
 RAISE EXCEPTION 'the Material Transaction ledger is append-only: % on % is refused', TG_OP,TG_TABLE_NAME USING ERRCODE='restrict_violation';
END $$;
CREATE TRIGGER factory_inventory_transactions_append_only BEFORE UPDATE OR DELETE ON factory_inventory_transactions FOR EACH ROW EXECUTE FUNCTION factory_inventory_ledger_refuse_change();
CREATE TRIGGER factory_inventory_transactions_no_truncate BEFORE TRUNCATE ON factory_inventory_transactions FOR EACH STATEMENT EXECUTE FUNCTION factory_inventory_ledger_refuse_change();
CREATE TRIGGER factory_inventory_entries_append_only BEFORE UPDATE OR DELETE ON factory_inventory_transaction_entries FOR EACH ROW EXECUTE FUNCTION factory_inventory_ledger_refuse_change();
CREATE TRIGGER factory_inventory_entries_no_truncate BEFORE TRUNCATE ON factory_inventory_transaction_entries FOR EACH STATEMENT EXECUTE FUNCTION factory_inventory_ledger_refuse_change();

CREATE FUNCTION factory_inventory_ledger_check_balance() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE checked_id bigint;
BEGIN
 IF TG_TABLE_NAME='factory_inventory_transactions' THEN checked_id:=NEW.id;
 ELSE checked_id:=NEW.transaction_id; END IF;
 IF NOT EXISTS(SELECT 1 FROM factory_inventory_transaction_entries WHERE transaction_id=checked_id) THEN
  RAISE EXCEPTION 'material transaction % has no entries',checked_id USING ERRCODE='check_violation';
 END IF;
 IF EXISTS(SELECT 1 FROM factory_inventory_transaction_entries WHERE transaction_id=checked_id GROUP BY native_unit_id HAVING sum(native_quantity)<>0) THEN
  RAISE EXCEPTION 'material transaction % does not balance',checked_id USING ERRCODE='check_violation';
 END IF;
 RETURN NULL;
END $$;
CREATE CONSTRAINT TRIGGER factory_inventory_transactions_balanced AFTER INSERT ON factory_inventory_transactions DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION factory_inventory_ledger_check_balance();
CREATE CONSTRAINT TRIGGER factory_inventory_entries_balanced AFTER INSERT ON factory_inventory_transaction_entries DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION factory_inventory_ledger_check_balance();

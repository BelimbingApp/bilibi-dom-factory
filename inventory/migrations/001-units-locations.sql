-- Units of measure and stock locations: the end state of Bilimbi's
-- factory_inventory_units (with retirement) and factory_inventory_locations.
-- Every row belongs to one company of one tenant; the tenant is carried so a
-- row can never name a company outside it.
CREATE TABLE factory_inventory_units (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 tenant_id bigint NOT NULL,
 company_id bigint NOT NULL,
 code text NOT NULL CHECK(code = btrim(code) AND length(code) BETWEEN 1 AND 32),
 name text NOT NULL CHECK(length(btrim(name)) > 0 AND length(name) <= 255),
 retired_at timestamptz,
 created_at timestamptz NOT NULL DEFAULT now(),
 updated_at timestamptz NOT NULL DEFAULT now(),
 CONSTRAINT factory_inventory_units_company_foreign FOREIGN KEY(tenant_id,company_id) REFERENCES companies(tenant_id,id) ON DELETE RESTRICT,
 CONSTRAINT factory_inventory_units_company_id_code_unique UNIQUE(company_id,code),
 -- The anchor a material's native unit and a conversion will reference.
 CONSTRAINT factory_inventory_units_company_id_id_unique UNIQUE(company_id,id)
);

CREATE TABLE factory_inventory_locations (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 tenant_id bigint NOT NULL,
 company_id bigint NOT NULL,
 code text NOT NULL CHECK(code = upper(btrim(code)) AND length(code) BETWEEN 1 AND 64),
 name text NOT NULL CHECK(length(btrim(name)) > 0 AND length(name) <= 255),
 created_at timestamptz NOT NULL DEFAULT now(),
 updated_at timestamptz NOT NULL DEFAULT now(),
 CONSTRAINT factory_inventory_locations_company_foreign FOREIGN KEY(tenant_id,company_id) REFERENCES companies(tenant_id,id) ON DELETE RESTRICT,
 CONSTRAINT factory_inventory_locations_company_id_code_unique UNIQUE(company_id,code),
 CONSTRAINT factory_inventory_locations_company_id_id_unique UNIQUE(company_id,id)
);

-- A code is how conversions and postings name a unit or location for good
-- (Bilimbi renames only a unit's name), and a retired unit stays retired.
CREATE FUNCTION factory_inventory_keep_identity() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
 IF NEW.id IS DISTINCT FROM OLD.id OR NEW.tenant_id IS DISTINCT FROM OLD.tenant_id
    OR NEW.company_id IS DISTINCT FROM OLD.company_id OR NEW.code IS DISTINCT FROM OLD.code THEN
  RAISE EXCEPTION '% rows keep their company and code', TG_TABLE_NAME USING ERRCODE = 'integrity_constraint_violation';
 END IF;
 IF TG_TABLE_NAME = 'factory_inventory_units' AND OLD.retired_at IS NOT NULL AND NEW.retired_at IS DISTINCT FROM OLD.retired_at THEN
  RAISE EXCEPTION 'A retired unit stays retired' USING ERRCODE = 'integrity_constraint_violation';
 END IF;
 RETURN NEW;
END $$;
CREATE TRIGGER factory_inventory_units_keep_identity BEFORE UPDATE ON factory_inventory_units FOR EACH ROW EXECUTE FUNCTION factory_inventory_keep_identity();
CREATE TRIGGER factory_inventory_locations_keep_identity BEFORE UPDATE ON factory_inventory_locations FOR EACH ROW EXECUTE FUNCTION factory_inventory_keep_identity();

-- Bilimbi Inventory's lot and unit identities, with unit dimensions, and the
-- transform genealogy links between stock entries. Identities and links are
-- append-only like the ledger, and every reference stays company-local.
CREATE TABLE factory_inventory_identities (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 tenant_id bigint NOT NULL,
 company_id bigint NOT NULL,
 material_id bigint NOT NULL,
 source_transaction_id bigint NOT NULL,
 kind varchar(8) NOT NULL,
 code varchar(255) NOT NULL,
 dimensions jsonb NOT NULL DEFAULT '{}'::jsonb,
 CONSTRAINT factory_inventory_identities_company_foreign FOREIGN KEY(tenant_id,company_id) REFERENCES companies(tenant_id,id),
 CONSTRAINT factory_inventory_identities_material_foreign FOREIGN KEY(company_id,material_id) REFERENCES factory_inventory_materials(company_id,id),
 CONSTRAINT factory_inventory_identities_source_foreign FOREIGN KEY(company_id,source_transaction_id) REFERENCES factory_inventory_transactions(company_id,id),
 CONSTRAINT factory_inventory_identities_company_id_material_id_code_unique UNIQUE(company_id,material_id,code),
 CONSTRAINT factory_inventory_identities_material_identity_unique UNIQUE(company_id,id,material_id),
 CONSTRAINT factory_inventory_identities_kind CHECK(kind IN ('lot','unit')),
 CONSTRAINT factory_inventory_identities_code CHECK(btrim(code)<>''),
 CONSTRAINT factory_inventory_identity_dimensions_shape CHECK(
   jsonb_typeof(dimensions)='object' AND (kind='unit' OR dimensions='{}'::jsonb)
   AND dimensions - 'width' - 'length' - 'thickness' = '{}'::jsonb)
);
CREATE INDEX factory_inventory_identities_source_index ON factory_inventory_identities(company_id,source_transaction_id);
CREATE TRIGGER factory_inventory_identities_append_only BEFORE UPDATE OR DELETE ON factory_inventory_identities FOR EACH ROW EXECUTE FUNCTION factory_inventory_ledger_refuse_change();
CREATE TRIGGER factory_inventory_identities_no_truncate BEFORE TRUNCATE ON factory_inventory_identities FOR EACH STATEMENT EXECUTE FUNCTION factory_inventory_ledger_refuse_change();

-- A stock entry may name an identity of its own material; boundary and
-- variance entries never do.
ALTER TABLE factory_inventory_transaction_entries ADD COLUMN identity_id bigint;
ALTER TABLE factory_inventory_transaction_entries ADD CONSTRAINT factory_inventory_entries_identity_foreign FOREIGN KEY(company_id,identity_id,material_id) REFERENCES factory_inventory_identities(company_id,id,material_id);
ALTER TABLE factory_inventory_transaction_entries ADD CONSTRAINT factory_inventory_transaction_entries_identity_stock CHECK(identity_id IS NULL OR role='stock');
ALTER TABLE factory_inventory_transaction_entries ADD CONSTRAINT factory_inventory_entries_transaction_entry_unique UNIQUE(company_id,transaction_id,id);
CREATE INDEX factory_inventory_entries_identity_index ON factory_inventory_transaction_entries(company_id,identity_id) WHERE identity_id IS NOT NULL;

-- A link joins an input and an output entry of the same transform.
CREATE TABLE factory_inventory_genealogy_links (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 tenant_id bigint NOT NULL,
 company_id bigint NOT NULL,
 transaction_id bigint NOT NULL,
 input_entry_id bigint NOT NULL,
 output_entry_id bigint NOT NULL,
 CONSTRAINT factory_inventory_genealogy_links_company_foreign FOREIGN KEY(tenant_id,company_id) REFERENCES companies(tenant_id,id),
 CONSTRAINT factory_inventory_genealogy_links_transaction_id_foreign FOREIGN KEY(company_id,transaction_id) REFERENCES factory_inventory_transactions(company_id,id),
 CONSTRAINT factory_inventory_genealogy_links_input_entry_id_foreign FOREIGN KEY(company_id,transaction_id,input_entry_id) REFERENCES factory_inventory_transaction_entries(company_id,transaction_id,id),
 CONSTRAINT factory_inventory_genealogy_links_output_entry_id_foreign FOREIGN KEY(company_id,transaction_id,output_entry_id) REFERENCES factory_inventory_transaction_entries(company_id,transaction_id,id),
 CONSTRAINT factory_inventory_genealogy_links_input_output_unique UNIQUE(input_entry_id,output_entry_id),
 CONSTRAINT factory_inventory_genealogy_links_distinct CHECK(input_entry_id<>output_entry_id)
);
CREATE INDEX factory_inventory_genealogy_links_output_index ON factory_inventory_genealogy_links(output_entry_id);
CREATE INDEX factory_inventory_genealogy_links_transaction_index ON factory_inventory_genealogy_links(company_id,transaction_id);
CREATE TRIGGER factory_inventory_genealogy_links_append_only BEFORE UPDATE OR DELETE ON factory_inventory_genealogy_links FOR EACH ROW EXECUTE FUNCTION factory_inventory_ledger_refuse_change();
CREATE TRIGGER factory_inventory_genealogy_links_no_truncate BEFORE TRUNCATE ON factory_inventory_genealogy_links FOR EACH STATEMENT EXECUTE FUNCTION factory_inventory_ledger_refuse_change();

-- Bilimbi ProductDefinition's final schema, without legacy resource kinds.
-- Inventory references are opaque IDs validated through its facade; this
-- module does not reach into its sibling's tables.
CREATE TABLE factory_products (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 tenant_id bigint NOT NULL,
 company_id bigint NOT NULL,
 item_id bigint NOT NULL CHECK(item_id > 0),
 code varchar(64) NOT NULL CHECK(length(btrim(code)) > 0),
 name varchar(255) NOT NULL CHECK(length(btrim(name)) > 0),
 inserted_at timestamptz NOT NULL DEFAULT now(),
 updated_at timestamptz NOT NULL DEFAULT now(),
 FOREIGN KEY(tenant_id,company_id) REFERENCES companies(tenant_id,id) ON DELETE RESTRICT,
 CONSTRAINT factory_products_company_code_unique UNIQUE(company_id,code),
 CONSTRAINT factory_products_company_item_unique UNIQUE(company_id,item_id),
 UNIQUE(tenant_id,company_id,id)
);
CREATE TABLE factory_resource_types (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 tenant_id bigint NOT NULL,
 company_id bigint NOT NULL,
 code varchar(64) NOT NULL CHECK(length(btrim(code)) > 0),
 name varchar(255) NOT NULL CHECK(length(btrim(name)) > 0),
 property_definitions jsonb NOT NULL DEFAULT '[]' CHECK(jsonb_typeof(property_definitions)='array'),
 retired_at timestamptz,
 inserted_at timestamptz NOT NULL DEFAULT now(),
 updated_at timestamptz NOT NULL DEFAULT now(),
 FOREIGN KEY(tenant_id,company_id) REFERENCES companies(tenant_id,id) ON DELETE RESTRICT,
 CONSTRAINT factory_resource_types_company_code_unique UNIQUE(company_id,code),
 UNIQUE(tenant_id,company_id,id)
);
CREATE TABLE factory_resources (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 tenant_id bigint NOT NULL,
 company_id bigint NOT NULL,
 code varchar(64) NOT NULL CHECK(length(btrim(code)) > 0),
 name varchar(255) NOT NULL CHECK(length(btrim(name)) > 0),
 resource_type_id bigint NOT NULL,
 properties jsonb NOT NULL DEFAULT '{}' CHECK(jsonb_typeof(properties)='object'),
 retired_at timestamptz,
 inserted_at timestamptz NOT NULL DEFAULT now(),
 updated_at timestamptz NOT NULL DEFAULT now(),
 FOREIGN KEY(tenant_id,company_id) REFERENCES companies(tenant_id,id) ON DELETE RESTRICT,
 CONSTRAINT factory_resources_resource_type_id_fkey FOREIGN KEY(tenant_id,company_id,resource_type_id)
 REFERENCES factory_resource_types(tenant_id,company_id,id) ON DELETE RESTRICT,
 CONSTRAINT factory_resources_company_code_unique UNIQUE(company_id,code)
);
CREATE INDEX factory_resources_type_index ON factory_resources(tenant_id,company_id,resource_type_id);
CREATE TABLE factory_formula_revisions (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 tenant_id bigint NOT NULL,
 company_id bigint NOT NULL,
 product_id bigint NOT NULL,
 version integer NOT NULL CHECK(version > 0),
 lines jsonb NOT NULL CHECK(jsonb_typeof(lines)='array' AND jsonb_array_length(lines)>0),
 process_config jsonb NOT NULL CHECK(jsonb_typeof(process_config)='object'),
 inserted_at timestamptz NOT NULL DEFAULT now(),
 FOREIGN KEY(tenant_id,company_id) REFERENCES companies(tenant_id,id) ON DELETE RESTRICT,
 FOREIGN KEY(tenant_id,company_id,product_id) REFERENCES factory_products(tenant_id,company_id,id) ON DELETE RESTRICT,
 CONSTRAINT factory_formula_revisions_product_version_unique UNIQUE(product_id,version)
);
CREATE TABLE factory_routing_revisions (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 tenant_id bigint NOT NULL,
 company_id bigint NOT NULL,
 product_id bigint NOT NULL,
 version integer NOT NULL CHECK(version > 0),
 operations jsonb NOT NULL CHECK(jsonb_typeof(operations)='array' AND jsonb_array_length(operations)>0),
 process_config jsonb NOT NULL CHECK(jsonb_typeof(process_config)='object'),
 inserted_at timestamptz NOT NULL DEFAULT now(),
 FOREIGN KEY(tenant_id,company_id) REFERENCES companies(tenant_id,id) ON DELETE RESTRICT,
 FOREIGN KEY(tenant_id,company_id,product_id) REFERENCES factory_products(tenant_id,company_id,id) ON DELETE RESTRICT,
 CONSTRAINT factory_routing_revisions_product_version_unique UNIQUE(product_id,version)
);
-- Preserve the immutable-revision contract even for accidental direct writes.
CREATE FUNCTION factory_product_definition_immutable() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
 RAISE EXCEPTION 'Product definition revisions are immutable';
END;
$$;
CREATE TRIGGER factory_formula_revisions_immutable BEFORE UPDATE OR DELETE OR TRUNCATE
 ON factory_formula_revisions FOR EACH STATEMENT EXECUTE FUNCTION factory_product_definition_immutable();
CREATE TRIGGER factory_routing_revisions_immutable BEFORE UPDATE OR DELETE OR TRUNCATE
 ON factory_routing_revisions FOR EACH STATEMENT EXECUTE FUNCTION factory_product_definition_immutable();
